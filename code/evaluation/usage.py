"""Write code/evaluation/usage_report.md for the final full-dataset run.

    python code/evaluation/usage.py

Runs the production pipeline on dataset/deletion_requests.csv exactly as
`python code/main.py` does, records every model response the run relied on
(served from cache or network), and reports per-model and overall calls, tokens
and estimated cost — both for this (warm) run and for a cold run from an empty
cache. Development-time calls (prompt experiments, the intent audit) are
summarized separately from code/cache/usage.jsonl.
"""
from __future__ import annotations

import json
import sys
import time
from collections import defaultdict
from pathlib import Path

CODE = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(CODE))

from exorcist.auditor import Auditor, read_requests  # noqa: E402
from exorcist.config import CACHE_DIR, DATASET_DIR  # noqa: E402
from exorcist.llm import PRICES  # noqa: E402

REPORT = Path(__file__).resolve().parent / "usage_report.md"


def cost(model, pin, pout):
    p_in, p_out = PRICES.get(model, (0.0, 0.0))
    return pin / 1e6 * p_in + pout / 1e6 * p_out


def table(groups: dict, n_requests: int) -> list[str]:
    out = ["| Provider / model | Purpose | Calls | Input tokens | Output tokens | Total tokens | Est. cost (USD) |",
           "|---|---|---|---|---|---|---|"]
    tot = [0, 0, 0, 0.0]
    for (model, purpose), g in sorted(groups.items()):
        c = cost(model, g["in"], g["out"])
        out.append(f"| groq / `{model}` | {purpose} | {g['calls']} | {g['in']:,} | {g['out']:,} | "
                   f"{g['in'] + g['out']:,} | ${c:.4f} |")
        tot[0] += g["calls"]; tot[1] += g["in"]; tot[2] += g["out"]; tot[3] += c
    out.append(f"| **Overall** | | **{tot[0]}** | **{tot[1]:,}** | **{tot[2]:,}** | **{tot[1] + tot[2]:,}** | **${tot[3]:.4f}** |")
    out.append("")
    out.append(f"- Requests: **{n_requests}** · average tokens per request: **{(tot[1] + tot[2]) / n_requests:,.1f}** · "
               f"average cost per request: **${tot[3] / n_requests:.6f}**")
    return out


def group(entries):
    g = defaultdict(lambda: {"calls": 0, "in": 0, "out": 0})
    for e in entries:
        purpose = "screenshot extraction (VLM)" if e["purpose"].startswith("vision") else \
                  "intent fallback (LLM)" if e["purpose"] == "intent" else e["purpose"]
        k = (e["model"], purpose)
        g[k]["calls"] += 1
        g[k]["in"] += e["usage"].get("prompt_tokens", 0)
        g[k]["out"] += e["usage"].get("completion_tokens", 0)
    return g


def main() -> int:
    t0 = time.perf_counter()
    aud = Auditor()
    reqs = read_requests(DATASET_DIR / "deletion_requests.csv")
    aud.audit(reqs)
    wall = time.perf_counter() - t0
    used = aud.llm.used
    net, hit = aud.llm.calls["network"], aud.llm.calls["cache"]

    dev = defaultdict(lambda: {"calls": 0, "in": 0, "out": 0})
    log = CACHE_DIR / "usage.jsonl"
    if log.exists():
        for line in log.read_text(encoding="utf-8").splitlines():
            e = json.loads(line)
            purpose = "screenshot extraction (VLM)" if e["purpose"].startswith("vision") else e["purpose"]
            k = (e["model"], purpose)
            dev[k]["calls"] += 1
            dev[k]["in"] += e["prompt_tokens"]
            dev[k]["out"] += e["completion_tokens"]

    md = [
        "# Token Usage and Cost Report",
        "",
        f"_Generated by `python code/evaluation/usage.py` on {time.strftime('%Y-%m-%d %H:%M UTC', time.gmtime())}._",
        "",
        "## Final full-dataset run (the run that produced `output.csv`)",
        "",
        f"- Input: `dataset/deletion_requests.csv` — {len(reqs)} requests · wall time **{wall:.2f} s** end-to-end.",
        "- Provider: **Groq** (OpenAI-compatible API). Models: `openai/gpt-oss-20b` (intent fallback) and "
        "`qwen/qwen3.8-27b` (vision, screenshot extraction). Temperature 0, fixed seed.",
        "- The deterministic core (loading, identity, discovery, state reconstruction, policy, planning) makes **no model calls**.",
        f"- Model responses relied on by this run: **{len(used)}** "
        f"({hit} served from the content-hash cache, {net} network calls in this process).",
        "",
        "### Per-model and overall totals for the final run (tokens of every response it relied on — equals a cold run from an empty cache)",
        "",
        *table(group(used), len(reqs)),
        "",
        "With the committed cache, rerunning `python code/main.py` makes **0** network calls and costs **$0**.",
        "",
        "## Development-time model usage (not part of the final run)",
        "",
        "All network calls made while building the system, from `code/cache/usage.jsonl`: the one-time screenshot "
        "extraction, prompt experiments, and the 398-text intent audit (rules vs LLM, 393/398 agreement; the 5 "
        "disagreements were LLM errors on deletion follow-ups, fixed in the prompt).",
        "",
        *table(dev, len(reqs)),
        "",
        "## Pricing assumptions",
        "",
        "| Model | Input $/1M tokens | Output $/1M tokens |",
        "|---|---|---|",
        *[f"| `{m}` | {p[0]} | {p[1]} |" for m, p in PRICES.items()],
        "",
        "Groq on-demand list prices used for estimation (see `code/exorcist/llm.py: PRICES`); the account used the "
        "free tier, so actual billed cost was $0.",
    ]
    REPORT.write_text("\n".join(md) + "\n", encoding="utf-8")
    print("\n".join(md))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
